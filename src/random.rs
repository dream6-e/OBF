    #[test]
    fn lcg_meets_hull_dobell_and_walks_the_whole_reduced_state_space() {
        // Hull-Dobell for m = 2^64, read off the constants the generator uses:
        // the increment is odd, and multiplier - 1 is a multiple of 2 (the only
        // prime factor of m) and of 4 (because 4 divides m). Together these say
        // the state sequence has full period 2^64 from every start state.
        assert_eq!(LCG_INCR % 2, 1, "increment must be coprime with 2^64");
        assert_eq!(
            (LCG_MULT - 1) % 2,
            0,
            "multiplier - 1 must hit every prime factor of m"
        );
        assert_eq!(
            (LCG_MULT - 1) % 4,
            0,
            "m is a multiple of 4, so this is required too"
        );

        // The 2^64 walk itself cannot be run, so the same three conditions are
        // re-checked on a truncated modulus where the full cycle is enumerable:
        // a period-1 state cycle would show up here immediately.
        const M: u64 = 1 << 20;
        let mult = LCG_MULT % M;
        let incr = LCG_INCR % M;
        assert_eq!(incr % 2, 1);
        assert_eq!((mult - 1) % 4, 0);
        let mut seen = vec![false; M as usize];
        let mut state = 0x1234_5678_u64 % M;
        let start = state;
        for step in 0..M {
            state = (state.wrapping_mul(mult).wrapping_add(incr)) % M;
            assert!(!seen[state as usize], "state repeated after {step} steps");
            seen[state as usize] = true;
        }
        assert_eq!(state, start, "the reduced cycle must close exactly at m");
    }

    #[test]
    fn bounded_draw_reads_high_bits_and_spreads_preimages_evenly() {
        // Top-bit semantics: bucket 1 of two starts exactly at 2^63, whereas a
        // remainder mapping would decide this sample from its low bits instead.
        assert_eq!(scale(1 << 63, 2), 1);
        assert_eq!(scale((1 << 63) - 1, 2), 0);
        assert_ne!(
            scale(1 << 63, 3),
            ((1_u128 << 63) % 3) as usize,
            "a remainder draw and a multiply-shift draw must not agree here"
        );
        for bound in 1..=4096usize {
            assert_eq!(scale(0, bound), 0, "zero maps into the first bucket");
            assert_eq!(scale(u64::MAX, bound), bound - 1, "the draw is onto");
            // Preimage sizes differ by at most one value: bucket i spans
            // [ceil(i * 2^64 / bound), ceil((i + 1) * 2^64 / bound)).
            // Bucket 0 is skipped: its lower boundary is zero, so there is
            // no value below it to attribute to a previous bucket.
            for bucket in 1..bound.min(8) {
                let span = 1_u128 << 64;
                let low = (span * bucket as u128 + bound as u128 - 1) / bound as u128;
                assert_eq!(
                    scale(low as u64, bound),
                    bucket,
                    "lower boundary of {bucket}"
                );
                assert_eq!(
                    scale(low as u64 - 1, bound),
                    bucket - 1,
                    "the value below a boundary belongs to the previous bucket"
                );
            }
        }
    }

    #[test]
    fn every_family_balances_the_bits_a_consumer_might_read() {
        // Fixed seeds, so the tolerated spread is not a flaky statistical claim:
        // it just has to prove the finalizers actually shuffle carries upward and
        // that no family leaves a bucket empty (an LCG without a finalizer sets
        // bit 0 to a strict alternation, which shows up here as 50/50 per bit but
        // a 64-bucket histogram of the raw state would not be flat).
        for seed in [1u64, 7001, 4242, u64::MAX] {
            for mut random in [Prng::new(seed), Prng::lcg(seed), Prng::sfc(seed)] {
                let mut counts = [0u32; 64];
                for _ in 0..65_536 {
                    // 65,536 draws over 64 buckets expect 1,024 each; +-15% is
                    // far outside what a broken finalizer would produce.
                    counts[(random.next_u64() & 63) as usize] += 1;
                }
                assert!(
                    counts.iter().all(|&count| (870..=1180).contains(&count)),
                    "{seed} {:?} low-6-bit histogram {counts:?}",
                    random.family()
                );
            }
        }

        // Why the finalizer exists: the raw state walk of the same constants has
        // bit 0 in exact alternation, so a consumer reading the state directly
        // would see a period-2 signal in its own low bit.
        let mut state = 7u64;
        for step in 0..64 {
            state = state.wrapping_mul(LCG_MULT).wrapping_add(LCG_INCR);
            assert_eq!(
                state & 1,
                step % 2,
                "the un-finalized LCG state is expected to alternate in bit 0"
            );
        }
    }

    #[test]
    fn families_are_independent_streams_per_seed() {
        // The constructors really do select different mixers, not just different
        // starting states of one mixer.
        assert_eq!(Prng::new(1).family(), Family::Xs);
        assert_eq!(Prng::lcg(1).family(), Family::Lcg);
        assert_eq!(Prng::sfc(1).family(), Family::Sfc);
        for seed in [0u64, 1, 4095, 7001, 7351, 65535, u64::MAX] {
            let xs: Vec<_> = (0..32)
                .scan(Prng::new(seed), |r, _| Some(r.next_u64()))
                .collect();
            let lcg: Vec<_> = (0..32)
                .scan(Prng::lcg(seed), |r, _| Some(r.next_u64()))
                .collect();
            let sfc: Vec<_> = (0..32)
                .scan(Prng::sfc(seed), |r, _| Some(r.next_u64()))
                .collect();
            assert!(
                xs.iter().zip(lcg.iter()).all(|(a, b)| a != b),
                "{seed}: xs == lcg"
            );
            assert!(
                xs.iter().zip(sfc.iter()).all(|(a, b)| a != b),
                "{seed}: xs == sfc"
            );
            assert!(
                lcg.iter().zip(sfc.iter()).all(|(a, b)| a != b),
                "{seed}: lcg == sfc"
            );
            // Each family must be a function of its seed, not of anything else.
            assert_eq!(
                lcg,
                (0..32)
                    .scan(Prng::lcg(seed), |r, _| Some(r.next_u64()))
                    .collect::<Vec<_>>()
            );
            assert_ne!(
                lcg,
                (0..32)
                    .scan(Prng::lcg(seed ^ 1), |r, _| Some(r.next_u64()))
                    .collect::<Vec<_>>()
            );
        }
    }

    #[test]
    fn routed_domains_never_share_the_shape_stream() {
        // Structural guard for the split: the transport/crypto and structure
        // modules must not sample from the default (output-shape) family again,
        // and the per-handler structure domains must not fall back to xorshift.
        // Read from source, because the family is chosen per construction site.
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let mut routed: std::collections::BTreeMap<String, (usize, usize, usize)> =
            std::collections::BTreeMap::new();
        let mut stack = vec![root.clone()];
        while let Some(dir) = stack.pop() {
            for entry in std::fs::read_dir(&dir).expect("source tree") {
                let path = entry.expect("dir entry").path();
                if path.is_dir() {
                    stack.push(path);
                    continue;
                }
                if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                    continue;
                }
                let relative = path
                    .strip_prefix(&root)
                    .expect("under src")
                    .display()
                    .to_string();
                let text = std::fs::read_to_string(&path).expect("source file");
                routed.insert(
                    relative,
                    (
                        text.matches("Prng::new(").count(),
                        text.matches("Prng::lcg(").count(),
                        text.matches("Prng::sfc(").count(),
                    ),
                );
            }
        }
        // Implementation files only: unit tests may sample from any family.
        let implementation: Vec<_> = routed
            .iter()
            .filter(|(name, _)| !name.contains("/tests") && !name.starts_with("vm/custom/tests"))
            .map(|(name, counts)| (name.as_str(), *counts))
            .collect();
        for (name, (plain, _lcg, sfc)) in &implementation {
            match *name {
                // Transport, cipher material and noise spelling ride sfc64.
                "vm/custom/transport.rs" | "vm/custom/chacha.rs" | "vm/custom/cipher.rs" => {
                    assert_eq!(*plain, 0, "{name} still samples from the shape stream");
                    assert!(*sfc > 0, "{name} never opens an sfc stream");
                }
                // Structure and per-handler mixing ride the full-period LCG.
                "vm/custom/lowering.rs" | "vm/custom/structure.rs" | "vm/custom/semantic.rs" => {
                    assert_eq!(*plain, 0, "{name} still samples from the shape stream");
                }
                _ => {}
            }
        }
        // No implementation file may sample a bounded value with a remainder any
        // more: `scale` is the only legal mapping, so a new domain cannot silently
        // reintroduce the bias this batch removed.
        let mut modulo = Vec::new();
        for (name, _) in &routed {
            if name.contains("/tests") || name.starts_with("vm/custom/tests") || name == "random.rs"
            {
                continue;
            }
            let text = std::fs::read_to_string(root.join(name)).expect("source file");
            for (line, content) in text.lines().enumerate() {
                if content.contains("next_u64() %") || content.contains("next_u64()%") {
                    modulo.push(format!("{name}:{}", line + 1));
                }
            }
        }
        assert!(
            modulo.is_empty(),
            "bounded draws must go through Prng::index (bias-free), found {modulo:?}"
        );

        // ...and the two families have to be live at all.
        let totals = routed
            .values()
            .fold((0, 0, 0), |a, b| (a.0 + b.0, a.1 + b.1, a.2 + b.2));
        assert!(totals.1 >= 6, "only {} lcg streams", totals.1);
        assert!(totals.2 >= 6, "only {} sfc streams", totals.2);
        assert!(
            totals.0 >= 6,
            "output-shape domains lost their stream: {totals:?}"
        );
    }

    #[test]
    fn reject_equal_forms_are_exact_and_never_read_twice() {
        // Every form the sampler can return must reject exactly when the two
        // sides differ, over the whole read domain - including the
        // cursor-advancing `left` side, which the pure flag gates.
        for pure in [false, true] {
            let mut rng = Prng::lcg(0x6b31_5f72_656a_6563);
            let mut seen = std::collections::BTreeSet::new();
            for _ in 0..400 {
                let text = rng.reject_unequal("a", "b", pure);
                seen.insert(text.clone());
                for (left, right) in [
                    (0i64, 0i64),
                    (0, 1),
                    (1, 0),
                    (255, 255),
                    (255, 254),
                    (65536, 65535),
                    (-3, -3),
                    (-3, 3),
                ] {
                    let rejects = eval_rejects(&text, left, right);
                    assert_eq!(
                        rejects,
                        left != right,
                        "{text} at a={left} b={right}: expected {}",
                        if left != right { "reject" } else { "accept" }
                    );
                }
            }
            // The impure family has four members and the pure one five; a
            // collapsed helper would leave the census short of that.
            assert!(
                seen.len() >= if pure { 5 } else { 4 },
                "pure={pure} only produced {seen:?}"
            );
        }
    }

    /// Evaluate one `reject_unequal` form for `a = left`, `b = right`. Returns
    /// whether the guard *rejects* (true when the sides differ), and panics on
    /// anything the helper cannot emit so a new form cannot slip through uncovered.
    fn eval_rejects(text: &str, left: i64, right: i64) -> bool {
        let trimmed = text.trim();
        if let Some(inner) = trimmed
            .strip_prefix("not(")
            .and_then(|body| body.strip_suffix(')'))
        {
            // not(a==b)
            let (a, b) = split(inner, "==").expect("not(a==b)");
            return side(a, left, right) != side(b, left, right);
        }
        if let Some(diff) = trimmed.strip_suffix("~=0") {
            // a-b~=0 or b-a~=0
            let (a, b) = split(diff, "-").expect("difference form");
            return side(a, left, right) - side(b, left, right) != 0;
        }
        if let Some(rest) = trimmed.strip_suffix("<b or b<a") {
            // The order form is emitted with the sides in place of `a`/`b`, so the
            // suffix check above covers the shape; `rest` must end at the left side.
            let _ = rest;
        }
        if trimmed.contains(" or ") {
            let (first, second) = trimmed.split_once(" or ").expect("order form");
            let (a, b) = split(first, "<").expect("a<b");
            let (c, d) = split(second, "<").expect("b<a");
            assert_eq!(
                (a, b, c, d),
                ("a", "b", "b", "a"),
                "unexpected order form {trimmed}"
            );
            return left < right || right < left;
        }
        let (a, b) = split(trimmed, "~=").expect("plain a~=b");
        assert_eq!((a, b), ("a", "b"));
        left != right
    }

    fn split<'a>(text: &'a str, op: &str) -> Option<(&'a str, &'a str)> {
        text.trim().split_once(op)
    }

    fn side(token: &str, left: i64, right: i64) -> i64 {
        match token.trim() {
            "a" => left,
            "b" => right,
            other => panic!("unexpected side {other:?}"),
        }
    }
