/// Sampling families behind the one stream type the tool uses.
///
/// Every layout decision used to ride a single xorshift64* stream, which meant
/// one recovered draw sequence was one step from rolling the others: same mixer,
/// same state, same period. Each domain still owns its own seed-tagged stream,
/// and now the domains also own different *mixing families*, so no single
/// recurrence explains names, validator shape and transport layout at once:
///
/// * [`Family::Xs`] - xorshift64*: output shape (identifier pools, name
///   shortening, method/key maps).
/// * [`Family::Lcg`] - a 64-bit linear congruential generator with Hull-Dobell
///   full-period constants and a bijective output finalizer: structure (the
///   validator's search tree, the lane route, register/operand lowering, the
///   per-handler routine arms).
/// * [`Family::Sfc`] - an sfc64-style four-word mixing state: transport and
///   noise (alphabets, segment order, key material, spelling pools).
///
/// A family is a *sampling* choice only: nothing here is presented as a cipher,
/// and no generated byte depends on anything but (seed, family, call order).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum Family {
    Xs,
    Lcg,
    Sfc,
}

/// Multiplier and increment of [`Family::Lcg`]. They stay `pub(crate)` so the
/// gate can verify the Hull-Dobell conditions on the constants the generator
/// actually uses instead of on restated copies: with m = 2^64 the conditions are
/// "increment is odd" and "multiplier - 1 is a multiple of every prime factor of
/// m, and of 4 because 4 divides m". Since 2 is the only prime factor of 2^64,
/// those two facts give a period of exactly 2^64 from every start state.
pub(crate) const LCG_MULT: u64 = 0x0000_0369_3ea1_f41d;
pub(crate) const LCG_INCR: u64 = 0x1405_7b7e_f767_814f;

/// Small deterministic generator for layout and identifier randomization.
///
/// This is deliberately not presented as a cryptographic primitive. Data
/// encryption and key derivation belong to a later milestone.
pub(crate) struct Prng {
    family: Family,
    state: u64,
    /// Mixing words, used only by [`Family::Sfc`].
    aux: [u64; 3],
}

/// Bounded draw with no division and no remainder: one 128-bit product of the
/// sample and the bound, keeping the high half (multiply-shift). The bucket
/// decision rides the top bits of the sample, so a family's structurally weak
/// low bits - an LCG's bit 0 alternates, `x * odd` keeps a xorshift's bit 0 at
/// period 2 - never pick a bucket, and every bucket's preimage differs by at
/// most one value. `raw % upper` instead hands its whole surplus to the first
/// `2^64 mod upper` buckets, which is exactly the kind of predictable structure
/// an analyst looks for when guessing how many arms a table has.
pub(crate) fn scale(raw: u64, upper: usize) -> usize {
    if upper <= 1 {
        0
    } else {
        (((raw as u128) * (upper as u128)) >> 64) as usize
    }
}

impl Prng {
    pub fn new(seed: u64) -> Self {
        Self::with_family(Family::Xs, seed)
    }

    /// Full-period LCG stream, see [`Family::Lcg`] and [`LCG_MULT`]/[`LCG_INCR`].
    pub fn lcg(seed: u64) -> Self {
        Self::with_family(Family::Lcg, seed)
    }

    /// sfc64-style stream, see [`Family::Sfc`].
    pub fn sfc(seed: u64) -> Self {
        Self::with_family(Family::Sfc, seed)
    }

    /// Which mixer this stream uses. Test-only: no generated byte depends on
    /// it, but the family-split gates below read it.
    #[cfg(test)]
    pub fn family(&self) -> Family {
        self.family
    }

    fn with_family(family: Family, seed: u64) -> Self {
        let state = if seed == 0 {
            0x9e37_79b9_7f4a_7c15
        } else {
            seed
        };
        let mut random = Self {
            family,
            state,
            aux: [0; 3],
        };
        if family == Family::Sfc {
            // The four mixing words come from one seed via splitmix64, then the
            // mixer is warmed up so a caller never sees the seeding arithmetic.
            let mut source = state;
            let mut words = [0u64; 4];
            for word in words.iter_mut() {
                source = source.wrapping_add(0x9e37_79b9_7f4a_7c15);
                let mut value = source;
                value = (value ^ (value >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
                value = (value ^ (value >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
                *word = value ^ (value >> 31);
            }
            random.state = words[0];
            random.aux = [words[1], words[2], words[3]];
            // An all-zero mixing state would be a fixed point; the seeding cannot
            // produce one, and this keeps that true for any future seeder.
            if random.state | random.aux[0] | random.aux[1] | random.aux[2] == 0 {
                random.state = 0x9e37_79b9_7f4a_7c15;
            }
            for _ in 0..12 {
                random.next_u64();
            }
        }
        random
    }

    pub fn next_u64(&mut self) -> u64 {
        match self.family {
            Family::Xs => {
                let mut value = self.state;
                value ^= value >> 12;
                value ^= value << 25;
                value ^= value >> 27;
                self.state = value;
                value.wrapping_mul(0x2545_f491_4f6c_dd1d)
            }
            Family::Lcg => {
                // One full-period state step, then a bijective finalizer. The
                // finalizer cannot shorten the state period (it is a permutation
                // of the state) and it removes the LCG's low-bit regularity from
                // every consumer, including any that reads bit 0 directly.
                self.state = self.state.wrapping_mul(LCG_MULT).wrapping_add(LCG_INCR);
                let mut value = self.state;
                value = (value ^ (value >> 33)).wrapping_mul(0xff51_afd7_ed55_8ccd);
                value = (value ^ (value >> 33)).wrapping_mul(0xc4a9_fdd1_9460_9c73);
                value ^ (value >> 33)
            }
            Family::Sfc => {
                // Four words: two shift/xor mixing words, one additive mixing word
                // and a counter folded into the output. Carries make the output
                // depend on all three mixing words at once.
                let result = self
                    .state
                    .wrapping_add(self.aux[0])
                    .wrapping_add(self.aux[2]);
                self.aux[2] = self.aux[2].wrapping_add(1).wrapping_add(result);
                let mixed = self.state ^ self.aux[0];
                self.state = self.aux[0].wrapping_add(self.aux[0] << 5);
                self.aux[0] = (self.aux[1] >> 3) ^ mixed;
                self.aux[1] = mixed.wrapping_add(result);
                result
            }
        }
    }

    /// One unbiased coin. Rides the top bit of the draw for the same reason
    /// [`scale`] does.
    pub fn coin(&mut self) -> bool {
        (self.next_u64() >> 63) != 0
    }

    pub fn index(&mut self, upper: usize) -> usize {
        scale(self.next_u64(), upper)
    }

    pub fn shuffle<T>(&mut self, values: &mut [T]) {
        for index in (1..values.len()).rev() {
            let other = self.index(index + 1);
            values.swap(index, other);
        }
    }

    pub fn unique_opcodes(&mut self, count: usize) -> Vec<u16> {
        let mut used = BTreeSet::new();
        let mut result = Vec::with_capacity(count);
        while result.len() < count {
            // 257..=65256, drawn through the same bias-free bounded sampler as
            // every other choice in the tool.
            let candidate = 257 + self.index(65_000) as u16;
            if used.insert(candidate) {
                result.push(candidate);
            }
        }
        result
    }

    /// Spell an exact non-negative integer using only forms accepted by the
    /// selected output target. Lua 5.1 receives decimal/hexadecimal forms;
    /// Luau may additionally receive binary digits and separators.
    pub fn integer_literal(&mut self, value: u64, luau: bool) -> String {
        match self.index(if luau { 3 } else { 2 }) {
            0 => value.to_string(),
            1 => format!("0x{value:x}"),
            2 => {
                let digits = format!("{value:b}");
                let first = {
                    let remainder = digits.len() % 4;
                    if remainder == 0 {
                        4
                    } else {
                        remainder
                    }
                };
                let mut result = String::from("0b");
                result.push_str(&digits[..first]);
                for chunk in digits.as_bytes()[first..].chunks(4) {
                    result.push('_');
                    result.push_str(std::str::from_utf8(chunk).expect("binary digits are UTF-8"));
                }
                result
            }
            _ => unreachable!(),
        }
    }

    /// Emit one of several side-effect-free dispatcher comparisons. Only the
    /// opcode comparison changes; handler evaluation order stays unchanged.
    pub fn dispatch_condition(&mut self, opcode: u16, luau: bool) -> String {
        self.dispatch_condition_for("o", opcode, luau)
    }

    /// Variable-parameterized form used by the semantic recipe dispatcher.
    /// The caller supplies an internal identifier, never user source.
    pub fn dispatch_condition_for(&mut self, variable: &str, opcode: u16, luau: bool) -> String {
        debug_assert!(variable
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_'));
        let literal = self.integer_literal(u64::from(opcode), luau);
        let mut result = String::new();
        match self.index(4) {
            0 => write!(result, "{variable}=={literal}").unwrap(),
            1 => write!(result, "{literal}=={variable}").unwrap(),
            2 => write!(result, "not({variable}~={literal})").unwrap(),
            3 => write!(result, "{variable}-{literal}==0").unwrap(),
            _ => unreachable!(),
        }
        result
    }

    /// Spell a "this field must match that value" guard's *reject condition* in
    /// one of several exactly equivalent forms: every result is true exactly when
    /// the two sides differ, which is what the emitted `if <it> then E()end` uses.
    ///
    /// The validator wrote every header, watermark and known-answer rejection as
    /// `left ~= right`, which turned the whole load-time check block into a single
    /// grep anchor: one search found every guard and its pass/fail polarity. The
    /// forms below differ in shape only - same predicate, same short-circuit
    /// structure, same fail-closed behaviour - and which one a site gets is a
    /// per-seed choice like every other spelling in the tool.
    ///
    /// Each form evaluates both sides exactly once. The two-sided order test is
    /// offered only when `pure` says neither side can have an effect, because the
    /// header reads (`b8()`, `b32()`, the segment cursors) advance a read position:
    /// reading one byte twice would shift every field behind it and turn a
    /// validator into a corrupter.
    pub fn reject_unequal(&mut self, left: &str, right: &str, pure: bool) -> String {
        // Both sides must be atomic for the difference forms to stay exact under
        // Lua's left-associative `+`/`-`: a caller that needs a compound operand
        // parenthesizes it. Commas are allowed only inside the parentheses of a
        // call, which is a single evaluation.
        for side in [left, right] {
            debug_assert!(side
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || b"_.#(),".contains(&byte)));
        }
        let text = match self.index(if pure { 5 } else { 4 }) {
            0 => format!("{left}~={right}"),
            1 => format!("not({left}=={right})"),
            2 => format!("{left}-{right}~=0"),
            3 => format!("{right}-{left}~=0"),
            _ => format!("{left}<{right} or {right}<{left}"),
        };
        text
    }

    /// Side-effect-free boundary test for the validator's binary search tree:
    /// `variable < bound` (below) or its exact complement `variable >= bound`.
    /// Each rides in one of several spellings and every bound is byte-sized, so
    /// all forms stay exact on both targets (no double rounding is involved).
    pub fn boundary_condition(
        &mut self,
        variable: &str,
        bound: u16,
        below: bool,
        luau: bool,
    ) -> String {
        debug_assert!(variable
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_'));
        let literal = self.integer_literal(u64::from(bound), luau);
        let mut result = String::new();
        if below {
            match self.index(5) {
                0 => write!(result, "{variable}<{literal}"),
                1 => write!(result, "{literal}>{variable}"),
                2 => write!(result, "not({variable}>={literal})"),
                3 => write!(result, "{variable}-{literal}<0"),
                _ => write!(result, "{literal}-{variable}>0"),
            }
        } else {
            match self.index(4) {
                0 => write!(result, "{variable}>={literal}"),
                1 => write!(result, "{literal}<={variable}"),
                2 => write!(result, "not({variable}<{literal})"),
                _ => write!(result, "{variable}-{literal}>=0"),
            }
        }
        .unwrap();
        result
    }
}

/// Fresh per-generation default, not a cryptographic key. A process-random
/// std hasher initializes the stream once; a bijective mixer of the atomic
/// counter avoids repeats within a process (until the u64 counter wraps).
/// Explicit user seeds never pass through this nondeterministic path.
pub(crate) fn fresh_seed() -> u64 {
    static BASE: OnceLock<u64> = OnceLock::new();
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let base = *BASE.get_or_init(|| {
        let mut hasher = RandomState::new().build_hasher();
        hasher.write_u32(std::process::id());
        hasher.write(
            &SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap_or_default()
                .as_nanos()
                .to_le_bytes(),
        );
        hasher.finish()
    });
    let mut value = base.wrapping_add(COUNTER.fetch_add(1, Ordering::Relaxed));
    value = (value ^ (value >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    value = (value ^ (value >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    value ^ (value >> 31)
}

